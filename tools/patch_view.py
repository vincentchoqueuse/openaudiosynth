#!/usr/bin/env python3
"""patch_view.py — human-readable view of a patch: what each setting means, in physical units, grouped by
section, with the values that differ from the defaults highlighted, envelopes drawn (SVG), the modulation
matrix as arrows, the effects, and optionally the measured sound (render + spectrogram).

  python3 tools/patch_view.py patches/piano_ambient.json             # text summary (terminal)
  python3 tools/patch_view.py patches/piano_ambient.json --html      # + build-host/plots/<name>.html
  python3 tools/patch_view.py patches/piano_ambient.json --html --render   # + measured sound, spectrogram
  options: --all (also list parameters left at their default), --out FILE.html

Reads the instrument description from docs/catalog.json (generated by synth_catalog).
"""
