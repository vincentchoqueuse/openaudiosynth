def html_view(patch, catalog, rows, show_all, sound=None):
    eng = catalog["engines"][patch["engine"]]
    adsr = adsr_groups(rows)
    rl = rl_groups(rows)
    cards = []
    secs = grouped(rows, True)
    for sec, items in secs.items():
        if sec == "mod" or sec.startswith("route"):
            continue
        chg = [r for r in items if r[3]]
        if not chg and not show_all and sec not in adsr:
            continue
        svg = ""
        if sec in adsr:
            a, d, s, r = adsr[sec]
            svg = svg_curve(adsr_points(a, d, s, r), label="attack / decay / sustain / release")
        elif sec in rl:
            rates, levels = rl[sec]
            svg = svg_curve(rl_points(rates, levels, db_domain=not sec.startswith("pitch")), label="rate / level")

        def row(r):
            n, d, v, ch = r
            return (f'<tr class="{"chg" if ch else "def"}"><td class="n">{html.escape(n)}</td>'
                    f'<td class="v">{html.escape(fmt(v, d))}<span>{html.escape(d.get("help", ""))}</span></td></tr>')
        shown = items if show_all else chg
        rest = [] if show_all else [r for r in items if not r[3]]
        body = f"<table>{''.join(row(r) for r in shown)}</table>"
        if rest:
            body += f"<details><summary>{len(rest)} at default</summary><table>{''.join(row(r) for r in rest)}</table></details>"
        cards.append(f'<section class="card"><h2>{html.escape(section_title(sec))}</h2>{svg}{body}</section>')
    mods = matrix(rows)
    if mods:
        cards.insert(0, '<section class="card"><h2>Modulation matrix</h2><ul class="mods">' +
                     "".join(f"<li>{html.escape(m)}</li>" for m in mods) + "</ul></section>")
    snd = ""
    if sound:
        png, metrics = sound
        snd = (f'<section class="card sound" style="grid-column:1/-1"><h2>Measured sound (audition)</h2>'
               f'<img alt="spectrogram" src="data:image/png;base64,{png}"><pre>{html.escape(metrics)}</pre></section>')
    aud = patch.get("audition", {})
    aud_line = f"audition: {html.escape(aud['notes'])}" if aud.get("notes") else ""
    changed = sum(1 for r in rows if r[3])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>{html.escape(patch.get('name', 'patch'))}</title>
<style>{CSS}</style></head><body><main>
<h1>{html.escape(patch.get('name', '?'))}</h1>
<p class="sub">engine <b>{html.escape(patch['engine'])}</b> — {html.escape(eng['description'])}</p>
<p class="desc">{html.escape(patch.get('description', ''))}</p>
<p class="sub">{changed} settings differ from the defaults (highlighted). {aud_line}</p>
<div class="grid">{snd}{''.join(cards)}</div></main></body></html>
"""


def measure(patch_path):
    render = os.path.join(ROOT, "build-host", "host", "synth_render")
    with tempfile.TemporaryDirectory() as tmp:
        wav = os.path.join(tmp, "audition.wav")
        subprocess.run([render, "--patch", patch_path, "--out", wav], check=True, capture_output=True, cwd=ROOT)
        r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "analyze.py"), wav, "--png"],
                           check=True, capture_output=True, text=True, cwd=ROOT)
        png = os.path.join(ROOT, "build-host", "plots", "audition.png")
        with open(png, "rb") as f:
            data = base64.b64encode(f.read()).decode()
        os.remove(png)
        metrics = "\n".join(l for l in r.stdout.splitlines()[1:])
        return data, metrics


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("patch")
    ap.add_argument("--html", action="store_true", help="write an HTML sheet (build-host/plots/<name>.html)")
    ap.add_argument("--out", help="HTML output path")
    ap.add_argument("--render", action="store_true", help="render the audition and embed its measurements")
    ap.add_argument("--all", action="store_true", help="also list the parameters left at their default")
    args = ap.parse_args()
    with open(args.patch) as f:
        patch = json.load(f)
    catalog = load_catalog()
    if patch.get("engine") not in catalog["engines"]:
        sys.exit(f"unknown engine {patch.get('engine')}")
    rows = resolve(patch, catalog)
    print(text_view(patch, catalog, rows, args.all))
    if args.html or args.out:
        sound = measure(os.path.abspath(args.patch)) if args.render else None
        out = args.out or os.path.join(ROOT, "build-host", "plots", os.path.basename(args.patch)[:-5] + ".html")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w") as f:
            f.write(html_view(patch, catalog, rows, args.all, sound))
        print(f"\nHTML sheet: {os.path.relpath(out, os.getcwd())}")


if __name__ == "__main__":
    main()
