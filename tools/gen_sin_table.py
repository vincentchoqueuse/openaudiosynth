#!/usr/bin/env python3
# gen_sin_table.py — generates dsp/core/sin_table.c: 2048-point sine + 1 guard point,
# rounded to float32. Usage: python3 tools/gen_sin_table.py > dsp/core/sin_table.c
import numpy as np

N = 2048
t = np.sin(2.0 * np.pi * np.arange(N + 1) / N).astype(np.float32)
t[N] = t[0]  # guard point: avoids a bounds check in the interpolation

print("/* sin_table.c — sine table (2048 points + 1 guard point), one full period.")
print(" * GENERATED by tools/gen_sin_table.py: do not edit by hand. */")
print('#include "fastmath.h"\n')
print("const float fm_sin_table[FM_SIN_SIZE + 1] = {")
for i in range(0, N + 1, 6):
    row = ", ".join("%.9gf" % float(v) if "." in "%.9g" % float(v) or "e" in "%.9g" % float(v)
                    else "%.1ff" % float(v) for v in t[i:i + 6])
    print("    " + row + ",")
print("};")
