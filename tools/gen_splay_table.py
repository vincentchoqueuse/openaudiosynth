#!/usr/bin/env python3
"""gen_splay_table.py — the interpolation kernel of the sample player (dsp/osc/splay.h): one side of a
Kaiser-windowed sinc, sinc(u) * I0(beta * sqrt(1 - (u/ZC)^2)) / I0(beta) for u in [0, ZC], tabulated with RES
points per zero crossing (read with linear interpolation). Writes dsp/osc/splay_table.c; rerun it only when
the constants below change (they must match splay.h).

    python3 tools/gen_splay_table.py
"""
import os
import numpy as np

ZC = 6       # zero crossings on each side (SPLAY_ZC)
RES = 64     # points per zero crossing (SPLAY_RES)
BETA = 7.0   # Kaiser window: about 70 dB of stopband attenuation

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
u = np.arange(ZC * RES + 2) / RES
w = np.where(u < ZC, np.i0(BETA * np.sqrt(np.clip(1 - (u / ZC) ** 2, 0, None))) / np.i0(BETA), 0.0)
k = np.sinc(u) * w
k[u >= ZC] = 0.0

lines = [
    "/* splay_table.c — GENERATED by tools/gen_splay_table.py: do not edit. One side of the windowed-sinc",
    f" * kernel of the sample player (splay.h): Kaiser beta {BETA}, {ZC} zero crossings, {RES} points per crossing. */",
    '#include "splay.h"',
    "",
    f"const float splay_kernel[SPLAY_ZC * SPLAY_RES + 2] = {{",
]
for i in range(0, len(k), 6):
    lines.append("    " + " ".join(f"{v:.9g}f," if "." in f"{v:.9g}" or "e" in f"{v:.9g}" else f"{v:.9g}.0f," for v in k[i:i + 6]))
lines.append("};")
with open(os.path.join(ROOT, "dsp", "osc", "splay_table.c"), "w") as f:
    f.write("\n".join(lines) + "\n")
