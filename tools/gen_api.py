#!/usr/bin/env python3
"""gen_api.py — writes docs/api.md, a one-page index of the portable code (dsp/, midi/): for every header,
its header comment and its public declarations (functions, static inline helpers, types, constants).
Read it before opening headers. Generated from the code, so it cannot drift; ctest (`api`) fails when it
is stale.

  python3 tools/gen_api.py           # rewrite docs/api.md
  python3 tools/gen_api.py --check   # exit 1 if docs/api.md is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "api.md")
ORDER = ["dsp/synth.h", "dsp/core", "dsp/osc", "dsp/filter", "dsp/env", "dsp/mod", "dsp/voice", "dsp/fx",
         "dsp/engines", "dsp", "midi"]


def header_comment(code):
    m = re.match(r"\s*/\*(.*?)\*/", code, re.S)
    if not m:
        return ""
    text = " ".join(l.strip().lstrip("*").strip() for l in m.group(1).splitlines())
    return re.sub(r"\s+", " ", text).strip()


def blank_comments(code):
    """Replaces comments by spaces of the same length (positions stay valid)."""
    blank = lambda m: re.sub(r"[^\n]", " ", m.group(0))
    return re.sub(r"//[^\n]*", blank, re.sub(r"/\*.*?\*/", blank, code, flags=re.S))


def doc_before(code, pos):
    """The comment that ends right before pos (only whitespace between), on one line."""
    before = code[:pos].rstrip()
    if before.endswith("*/"):
        start = before.rfind("/*")
        text = before[start + 2:-2]
    else:
        m = re.search(r"((?:^[ \t]*//[^\n]*\n?)+)$", code[:pos].rstrip(" \t"), re.M)
        if not m:
            return ""
        text = re.sub(r"^\s*//", "", m.group(1), flags=re.M)
    text = re.sub(r"\s+", " ", " ".join(l.strip().lstrip("*") for l in text.splitlines())).strip()
    return text if len(text) <= 220 else text[:217] + "..."


def declarations(code):
    bare = blank_comments(code)
    out = []
    # function prototypes and static inline definitions (signature only), with the comment above them
    for m in re.finditer(r"^(static inline\s+)?([A-Za-z_][\w\s\*]*?\b(\w+)\s*\([^;{)]*(?:\([^)]*\)[^;{)]*)*\))\s*[;{]",
                         bare, re.M):
        sig = re.sub(r"\s+", " ", m.group(2)).strip()
        if m.group(3) in ("if", "for", "while", "switch", "return", "sizeof") or sig.startswith(("return", "else")):
            continue
        out.append((sig, doc_before(code, m.start())))
    types = re.findall(r"\}\s*(\w+_t)\s*;", bare)
    consts = re.findall(r"^#define[ \t]+([A-Z][A-Z0-9_]+)[ \t]+([^\s][^\n]*)", bare, re.M)
    consts = [(n, v.strip()) for n, v in consts if not n.endswith("_H") and len(v) < 40]
    externs = [re.sub(r"\s+", " ", e) for e in re.findall(r"^extern\s+([^;(]+);", bare, re.M)]
    return out, types, consts, externs


def headers():
    found = []
    for d in ("dsp", "midi"):
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            for f in files:
                if f.endswith(".h"):
                    found.append(os.path.relpath(os.path.join(base, f), ROOT))

    def key(p):
        for i, o in enumerate(ORDER):
            if p == o or os.path.dirname(p) == o:
                return (i, p)
        return (len(ORDER), p)

    return sorted(found, key=key)


def build():
    lines = ["# API index (generated by tools/gen_api.py, do not edit)", "",
             "Public declarations of the portable code, header by header. Engine parameters are in "
             "`docs/catalog.md`; conventions and rules in `CLAUDE.md` and `docs/adding_an_engine.md`.", ""]
    for h in headers():
        code = open(os.path.join(ROOT, h)).read()
        funcs, types, consts, externs = declarations(code)
        lines.append(f"## `{h}`")
        c = header_comment(code)
        if c:
            lines.append(c.split(" — ", 1)[-1] if " — " in c else c)
        if types:
            lines.append("- types: " + ", ".join(f"`{t}`" for t in types))
        if consts:
            lines.append("- constants: " + ", ".join(f"`{n}` = {v}" if len(v) < 14 else f"`{n}`" for n, v in consts))
        if externs:
            lines.append("- data: " + ", ".join(f"`{e}`" for e in externs))
        for f, doc in funcs:
            lines.append(f"- `{f}`" + (f" — {doc}" if doc else ""))
        lines.append("")
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("docs/api.md is out of date: run python3 tools/gen_api.py")
            return 1
        print("docs/api.md up to date")
        return 0
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
