#!/usr/bin/env python3
"""gen_font.py — rasterizes a TrueType font into anti-aliased bitmap fonts for the boards' screens: printable
ASCII (32..126), 4 bits of coverage per pixel, each glyph cropped to its ink box with its placement and advance.
The output is a C file read by target/h745/app/m4/gfx.c (font_t in gfx.h). Default font: DejaVu Sans (Bitstream
Vera license, which allows redistribution; copy in third_party/fonts/LICENSE_DEJAVU), shipped with matplotlib.

    .venv/bin/python tools/gen_font.py target/h745/app/m4/fonts_gen.c
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
import matplotlib

TTF_DIR = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
# name in C, file, pixel size
FONTS = [
    ("font_small", "DejaVuSans.ttf", 12),
    ("font_body", "DejaVuSans.ttf", 16),
    ("font_title", "DejaVuSans-Bold.ttf", 18),
    ("font_big", "DejaVuSans-Bold.ttf", 22),
]
FIRST, LAST = 32, 126


def render(path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = round(font.getlength(ch))
        box = font.getbbox(ch)  # ink box relative to the origin (top of the ascent)
        w, h = max(box[2] - box[0], 0), max(box[3] - box[1], 0)
        offset = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
            px = img.load()
            for y in range(h):
                row = [px[x, y] >> 4 for x in range(w)] + [0]  # 4 bits, padded to an even count
                for x in range(0, w, 2):
                    bits.append(row[x] << 4 | row[x + 1])
        glyphs.append((offset, w, h, box[0], box[1], adv))
    return ascent, descent, glyphs, bits


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "fonts_gen.c")
    lines = ["/* fonts_gen.c — GENERATED by tools/gen_font.py: do not edit. Anti-aliased bitmap fonts (4-bit coverage)",
             " * rasterized from DejaVu Sans (Bitstream Vera license: third_party/fonts/LICENSE_DEJAVU). */",
             '#include "gfx.h"', ""]
    for name, file, size in FONTS:
        ascent, descent, glyphs, bits = render(TTF_DIR / file, size)
        lines.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{")
        for i in range(0, len(bits), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for g in glyphs:
            lines.append("    {%d, %d, %d, %d, %d, %d}," % g)
        lines.append("};")
        lines.append(f"const font_t {name} = {{{name}_bits, {name}_glyphs, {ascent + descent}, {ascent}, "
                     f"{FIRST}, {LAST - FIRST + 1}}};")
        lines.append("")
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
